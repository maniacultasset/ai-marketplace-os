"""Colourways and matrix cells (DATABASE.md §5.2 :426-460; ADR-0007; S13 B9, B10).

`ColourwayRepository.upsert(style_id, colour_fact, position)` creates or updates the style's
colourway on its `colour_key` (lower-cased, trimmed colour value, generated by the database).
`MatrixCellRepository.upsert(...)` writes an available cell for a sellable child (it replaces a
derived gap on the same axes), and `.fill_gap(...)` writes one `unavailable/not_provided` cell
(`source='derived'`) only where no cell exists yet (T17), so a later import never downgrades a
cell another import made available. Both are idempotent and write nothing when unchanged.
"""

from __future__ import annotations

import json
import uuid
from collections.abc import Mapping
from typing import Any

from sqlalchemy import cast, func, literal, literal_column, text, tuple_
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import insert as pg_insert

from app.db.guard import TENANT_INFO_KEY, CrossTenantQueryError
from app.db.models.catalog import ProductColourway, VariantMatrixCell
from app.repositories.base import TenantScopedRepository


def _own(repo: TenantScopedRepository[Any]) -> None:
    if repo.db.info.get(TENANT_INFO_KEY) != repo.tenant_id:
        raise CrossTenantQueryError("a variant write for another tenant's unit of work")


class ColourwayRepository(TenantScopedRepository[ProductColourway]):
    model = ProductColourway

    async def upsert(
        self, style_id: uuid.UUID, colour_fact: Mapping[str, Any], position: int
    ) -> uuid.UUID:
        """The colourway of `style_id` whose key is the fact's value, lower-cased and trimmed;
        its `color` fact is replaced only when value, normalized value or source changed."""
        _own(self)
        fact = cast(literal(json.dumps(dict(colour_fact))), JSONB)
        stmt = pg_insert(ProductColourway).values(
            tenant_id=self.tenant_id,
            style_product_id=style_id,
            attributes=func.jsonb_build_object("color", fact),
            position=position,
        )
        table = ProductColourway.__table__
        old = table.c.attributes["color"]
        new = stmt.excluded.attributes["color"]
        changed = tuple_(old["value"], old["normalized"], old["source"]).is_distinct_from(
            tuple_(new["value"], new["normalized"], new["source"])
        )
        upsert = stmt.on_conflict_do_update(
            index_elements=[table.c.tenant_id, table.c.style_product_id, table.c.colour_key],
            index_where=table.c.deleted_at.is_(None),
            set_={"attributes": table.c.attributes.op("||")(stmt.excluded.attributes)},
            where=changed,
        ).returning(table.c.id)
        written: uuid.UUID | None = (await self.db.execute(upsert)).scalar_one_or_none()
        if written is not None:
            return written
        key = str(colour_fact.get("value", "")).strip().lower()
        found: uuid.UUID = (
            await self.db.execute(
                self._select()
                .where(
                    ProductColourway.style_product_id == style_id,
                    ProductColourway.colour_key == key,
                    ProductColourway.deleted_at.is_(None),
                )
                .with_only_columns(ProductColourway.id)
            )
        ).scalar_one()
        return found

    async def live_ids(self, style_id: uuid.UUID) -> list[uuid.UUID]:
        """Every live colourway of `style_id`, in position order (a gap fill covers the stored
        family, not only one file's colours)."""
        stmt = (
            self._select()
            .where(
                ProductColourway.style_product_id == style_id,
                ProductColourway.deleted_at.is_(None),
            )
            .with_only_columns(ProductColourway.id)
            .order_by(ProductColourway.position, ProductColourway.id)
        )
        return list((await self.db.execute(stmt)).scalars())


class MatrixCellRepository(TenantScopedRepository[VariantMatrixCell]):
    model = VariantMatrixCell

    async def upsert(
        self,
        style_id: uuid.UUID,
        colourway_id: uuid.UUID | None,
        size_key: str | None,
        child_id: uuid.UUID,
        status: str = "available",
    ) -> None:
        """The available cell of `child_id` on `(colourway, size)`."""
        _own(self)
        if status != "available":
            raise ValueError("upsert writes an available cell; gaps go through fill_gap")
        stmt = pg_insert(VariantMatrixCell).values(
            tenant_id=self.tenant_id,
            style_product_id=style_id,
            colourway_id=colourway_id,
            size_key=size_key,
            availability="available",
            variant_product_id=child_id,
            unavailable_reason=None,
            source="seller",
            evidence_ref=None,
        )
        table = VariantMatrixCell.__table__
        names = (
            "availability",
            "variant_product_id",
            "unavailable_reason",
            "source",
            "evidence_ref",
        )
        changed = tuple_(*(table.c[n] for n in names)).is_distinct_from(
            tuple_(*(stmt.excluded[n] for n in names))
        )
        await self.db.execute(
            stmt.on_conflict_do_update(
                constraint="vmc_cell_uq",
                set_={n: stmt.excluded[n] for n in names},
                where=changed,
            )
        )

    async def fill_gap(
        self,
        style_id: uuid.UUID,
        colourway_id: uuid.UUID | None,
        size_key: str | None,
        evidence_ref: str,
    ) -> bool:
        """One derived `not_provided` cell where none exists; True when it was written."""
        _own(self)
        stmt: Any = (
            pg_insert(VariantMatrixCell)
            .values(
                tenant_id=self.tenant_id,
                style_product_id=style_id,
                colourway_id=colourway_id,
                size_key=size_key,
                availability="unavailable",
                variant_product_id=None,
                unavailable_reason="not_provided",
                source="derived",
                evidence_ref=evidence_ref,
            )
            .on_conflict_do_nothing(constraint="vmc_cell_uq")
            .returning(literal_column("1"))
        )
        return (await self.db.execute(stmt)).first() is not None

    async def check_now(self) -> None:
        """Run the deferred matrix check (VAR02) now, inside the caller's savepoint, then defer it
        again, so a bad child fails its own row instead of the batch's COMMIT."""
        await self.db.execute(text("SET CONSTRAINTS variant_matrix_complete IMMEDIATE"))
        await self.db.execute(text("SET CONSTRAINTS variant_matrix_complete DEFERRED"))
