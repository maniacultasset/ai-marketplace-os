def _updated_at_trigger(table: str) -> str:
    return (
        f"CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.{table} "
        "FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()"
    )


# ---- RULES: rules_revision_seq + rules (DATABASE.md §5.2; A§4; KI-B key and versions) ----
# tenant_id NULL = a platform rule. rule_type, subject and pack are promoted from rule_def, each
# tied to it by a CHECK, so the scope key tells two image checks or two claim rules apart. A
# missing JSON key yields NULL and would pass a plain `=` CHECK, hence IS NOT DISTINCT FROM and
# coalesce(...). The subject per type: the attribute, the claim, the rule name, or slot:check.
RULE_TYPES: Final = (
    "'max_length', 'min_length', 'banned_terms', 'required_attribute', 'max_items', "
    "'min_items', 'allowed_values', 'conditional_required', 'cross_field', "
    "'claim_requires_attribute', 'image_requirement', 'pattern', 'fact_source', "
    "'fact_backed_attribute'"
)
