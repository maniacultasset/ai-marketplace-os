    "CREATE SEQUENCE public.rules_revision_seq AS integer",
    f"""
    CREATE TABLE public.rules (
      id uuid NOT NULL DEFAULT gen_random_uuid(),
      tenant_id uuid,
      marketplace text NOT NULL,
      category text,
      field text NOT NULL,
      rule_type text NOT NULL,
      subject text NOT NULL DEFAULT '',
      pack text NOT NULL DEFAULT 'core',
      severity text NOT NULL DEFAULT 'error',
      version integer NOT NULL DEFAULT 1,
      enabled boolean NOT NULL DEFAULT true,
      revision integer NOT NULL DEFAULT nextval('public.rules_revision_seq'),
      rule_def jsonb NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now(),
      CONSTRAINT pk_rules PRIMARY KEY (id),
      CONSTRAINT fk_rules_tenant_id_tenants FOREIGN KEY (tenant_id)
        REFERENCES public.tenants (id) ON DELETE CASCADE,
      CONSTRAINT ck_rules_marketplace {MARKETPLACE_CHECK},
      CONSTRAINT ck_rules_severity CHECK (severity IN ('error', 'warning')),
      CONSTRAINT ck_rules_version CHECK (version >= 1),
      CONSTRAINT ck_rules_rule_def CHECK (jsonb_typeof(rule_def) = 'object'),
      CONSTRAINT ck_rules_rule_type CHECK (rule_type IN ({RULE_TYPES})),
      CONSTRAINT rules_type_matches CHECK (rule_type IS NOT DISTINCT FROM rule_def ->> 'type'),
      CONSTRAINT rules_subject_matches CHECK (
        subject ~ '^[a-z0-9_:*]{{0,96}}$'
        AND subject = coalesce(CASE rule_type
          WHEN 'image_requirement' THEN (rule_def ->> 'slot') || ':' || (rule_def ->> 'check')
          WHEN 'claim_requires_attribute' THEN rule_def ->> 'claim'
          WHEN 'cross_field' THEN rule_def ->> 'name'
          WHEN 'pattern' THEN rule_def ->> 'name'
          WHEN 'required_attribute' THEN rule_def ->> 'attribute'
          WHEN 'allowed_values' THEN rule_def ->> 'attribute'
          WHEN 'conditional_required' THEN rule_def ->> 'attribute'
          WHEN 'fact_source' THEN rule_def ->> 'attribute'
          WHEN 'fact_backed_attribute' THEN rule_def ->> 'attribute'
        END, '')
      ),
      CONSTRAINT rules_pack_matches CHECK (
        pack ~ '^[a-z_]{{1,32}}$' AND pack = coalesce(rule_def ->> 'pack', 'core')
      ),
      CONSTRAINT rules_images_field CHECK ((field = 'images') = (rule_type = 'image_requirement')),
      CONSTRAINT rules_tenant_types CHECK (
        tenant_id IS NULL OR rule_type IN ('banned_terms', 'claim_requires_attribute')
      ),
      CONSTRAINT rules_platform_only_regex CHECK (
        tenant_id IS NULL
        OR (rule_type <> 'pattern' AND (rule_def ->> 'match') IS DISTINCT FROM 'regex')
      ),
      CONSTRAINT rules_platform_cited CHECK (
        tenant_id IS NOT NULL
        OR coalesce(jsonb_typeof(rule_def -> 'policy_ref') = 'object', false)
      )
    )
    """,
