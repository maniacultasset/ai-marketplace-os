SLICES: Final[tuple[tuple[tuple[str, ...], tuple[str, ...]], ...]] = ((RULES_UP, RULES_DOWN),)


def upgrade() -> None:
    op.execute("SET lock_timeout = '5s'")
    for up, _ in SLICES:
        for statement in up:
            op.execute(statement)


def downgrade() -> None:
    op.execute("SET lock_timeout = '5s'")
    for _, down in reversed(SLICES):
        for statement in down:
            op.execute(statement)
