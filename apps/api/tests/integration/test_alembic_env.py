"""alembic/env.py on a real database: the round trip, the lock, the newer-database refusal, drift,
the offline SQL, the role switch and the alembic_version privileges (CANON.md:75, :136;
EXECUTION-PLAN.md:300-305; DATABASE.md:1813). Each test runs on its own scratch database."""

from __future__ import annotations

from collections.abc import Callable
from io import StringIO
from pathlib import Path
from typing import Any

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table
from sqlalchemy.exc import DBAPIError
from tests.alembic_helpers import write_revision

from .conftest import (
    SCRATCH_PREFIX,
    ScratchDb,
    assert_no_scratch_revision_in,
    scratch_database,
)

pytestmark = pytest.mark.allow_hosts(["localhost", "127.0.0.1", "::1"])

Conn = psycopg.Connection[tuple[Any, ...]]
MakeConfig = Callable[[Path | None], Config]
APP_ROLES = ("app_rw", "app_ro", "app_platform_ro")
DML = ("SELECT", "INSERT", "UPDATE", "DELETE")

ASSERT_LOCK_HELD = (
    "DO $$ BEGIN IF (SELECT count(*) FROM pg_locks WHERE locktype = 'advisory' AND granted "
    "AND pid = pg_backend_pid()) <> 1 OR current_setting('lock_timeout') <> '5s' "
    "THEN RAISE EXCEPTION 'lock not held'; END IF; END $$"
)
ASSERT_MIGRATOR = (
    "DO $$ BEGIN IF current_user <> 'migrator' OR session_user <> 'postgres' "
    "THEN RAISE EXCEPTION 'not migrator'; END IF; END $$"
)
CREATE_PROBE = "CREATE TABLE probe (id bigint PRIMARY KEY)"
DROP_PROBE = "DROP TABLE probe"


def _connect(db: ScratchDb) -> Conn:
    return psycopg.connect(db.libpq, autocommit=True, connect_timeout=5)


def _scalar(db: ScratchDb, query: str, *params: object) -> Any:
    with _connect(db) as conn:
        row = conn.execute(query, params or None).fetchone()
    return None if row is None else row[0]


def _has_table(db: ScratchDb, name: str) -> bool:
    return _scalar(db, "SELECT to_regclass(%s) IS NOT NULL", name) is True


def _version_rows(db: ScratchDb) -> list[str]:
    with _connect(db) as conn:
        return [r[0] for r in conn.execute("SELECT version_num FROM alembic_version").fetchall()]


def _public_relations(db: ScratchDb) -> list[str]:
    # Extension members (vector, pgcrypto, pg_trgm) are not ours.
    with _connect(db) as conn:
        rows = conn.execute(
            "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'v', 'S', 'm', 'p') "
            "AND NOT EXISTS (SELECT 1 FROM pg_depend d "
            "WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype = 'e') "
            "ORDER BY 1"
        ).fetchall()
    return [r[0] for r in rows]


def _privilege(db: ScratchDb, role: str, table: str, privilege: str) -> bool:
    return _scalar(db, "SELECT has_table_privilege(%s, %s, %s)", role, table, privilege) is True


def _seed_ahead(db: ScratchDb, revision: str) -> None:
    """A version table from a newer image, owned by migrator as env.py would have left it."""
    with _connect(db) as conn:
        conn.execute("CREATE TABLE alembic_version (version_num varchar(32) PRIMARY KEY)")
        conn.execute("INSERT INTO alembic_version VALUES (%s)", (revision,))
        conn.execute("ALTER TABLE alembic_version OWNER TO migrator")


def test_empty_head_round_trip_is_noop(alembic_env: MakeConfig, scratch_db: ScratchDb) -> None:
    cfg = alembic_env(None)
    command.upgrade(cfg, "head")
    command.check(cfg)
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    # Alembic 1.20 creates its (empty) version table on every online run; nothing else appears.
    assert _version_rows(scratch_db) == []
    assert _public_relations(scratch_db) == ["alembic_version"]


def test_round_trip_applies_reverts_reapplies(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    cfg = alembic_env(versions)
    command.upgrade(cfg, "head")
    assert _has_table(scratch_db, "probe")
    assert _version_rows(scratch_db) == ["s5a"]
    command.downgrade(cfg, "base")
    assert not _has_table(scratch_db, "probe")
    assert _version_rows(scratch_db) == []
    command.upgrade(cfg, "head")
    assert _has_table(scratch_db, "probe")
    assert _version_rows(scratch_db) == ["s5a"]


def test_migration_runs_holding_the_lock(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [ASSERT_LOCK_HELD, CREATE_PROBE], [DROP_PROBE])
    command.upgrade(alembic_env(versions), "head")
    assert _has_table(scratch_db, "probe")


def test_refuses_unknown_revision_in_database(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    from app.db.migrations import DatabaseAheadError

    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    _seed_ahead(scratch_db, "ffffffffffff")
    with pytest.raises(DatabaseAheadError) as info:
        command.upgrade(alembic_env(versions), "head")
    assert info.value.revision == "ffffffffffff"
    assert not _has_table(scratch_db, "probe")
    assert _version_rows(scratch_db) == ["ffffffffffff"]


@pytest.mark.parametrize("stored", ["0001", "0001_core", "head", "heads"])
def test_refuses_partial_or_symbolic_revision_in_database(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path, stored: str
) -> None:
    """A prefix of a known id, or Alembic's `head`/`heads` symbol, is still an id this code
    lacks: refused, never resolved to a known revision and skipped as "ok"."""
    from app.db.migrations import DatabaseAheadError

    versions = tmp_path / "versions"
    write_revision(versions, "0001_core_tenancy", [CREATE_PROBE], [DROP_PROBE])
    _seed_ahead(scratch_db, stored)
    with pytest.raises(DatabaseAheadError) as info:
        command.upgrade(alembic_env(versions), "head")
    assert info.value.revision == stored
    assert not _has_table(scratch_db, "probe")
    assert _version_rows(scratch_db) == [stored]


def test_check_fails_on_model_drift(alembic_env: MakeConfig) -> None:
    from app.db.base import metadata

    table = Table("drift_probe", metadata, Column("id", Integer, primary_key=True))
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="add_table"):
            command.check(alembic_env(None))
    finally:
        metadata.remove(table)
    assert "drift_probe" not in metadata.tables


def test_offline_sql_sets_lock_timeout_before_ddl(alembic_env: MakeConfig, tmp_path: Path) -> None:
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    cfg = alembic_env(versions)
    buffer = StringIO()
    cfg.output_buffer = buffer
    command.upgrade(cfg, "head", sql=True)
    rendered = buffer.getvalue()
    assert "SET lock_timeout = '5s';" in rendered
    assert rendered.index("SET lock_timeout = '5s';") < rendered.index("CREATE TABLE probe")
    assert "SET ROLE" not in rendered
    assert "REVOKE" not in rendered


def test_scratch_database_is_dropped(superuser_conn: Conn) -> None:
    with scratch_database(superuser_conn) as db:
        assert _scalar(db, "SELECT current_database()") == db.name
    gone = superuser_conn.execute(
        "SELECT count(*) FROM pg_database WHERE datname = %s", (db.name,)
    ).fetchone()
    assert gone == (0,)
    assert db.name.startswith(SCRATCH_PREFIX)
    assert_no_scratch_revision_in(superuser_conn)


def test_env_runs_as_migrator_owns_tables(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [ASSERT_MIGRATOR, CREATE_PROBE], [DROP_PROBE])
    command.upgrade(alembic_env(versions), "head")
    owner = _scalar(scratch_db, "SELECT tableowner FROM pg_tables WHERE tablename = 'probe'")
    assert owner == "migrator"
    for privilege in DML:
        assert _privilege(scratch_db, "app_rw", "probe", privilege), privilege
    for role in ("app_ro", "app_platform_ro"):
        assert not _privilege(scratch_db, role, "probe", "SELECT"), role


def _assert_version_table_locked_down(db: ScratchDb) -> None:
    owner = _scalar(db, "SELECT tableowner FROM pg_tables WHERE tablename = 'alembic_version'")
    assert owner == "migrator"
    for role in APP_ROLES:
        for privilege in (*DML, "TRUNCATE"):
            assert not _privilege(db, role, "alembic_version", privilege), (role, privilege)
    public = _scalar(
        db,
        "SELECT count(*) FROM pg_class c, aclexplode(c.relacl) a "
        "WHERE c.oid = 'alembic_version'::regclass AND a.grantee = 0",
    )
    assert public == 0


def test_version_table_privileges_after_upgrade(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    command.upgrade(alembic_env(None), "head")
    assert _version_rows(scratch_db) == []
    _assert_version_table_locked_down(scratch_db)

    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    command.upgrade(alembic_env(versions), "head")
    _assert_version_table_locked_down(scratch_db)


def test_version_table_privileges_after_failed_revision(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    """Revision 1 commits (one transaction per migration), revision 2 fails: the app roles
    still lose their default privileges on alembic_version, and the original error surfaces."""
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    write_revision(versions, "s5b", ["SELECT 1/0"], [], down_revision="s5a")
    with pytest.raises(DBAPIError) as info:
        command.upgrade(alembic_env(versions), "head")
    assert getattr(info.value.orig, "sqlstate", None) == "22012"
    assert _version_rows(scratch_db) == ["s5a"]
    assert _has_table(scratch_db, "probe")
    _assert_version_table_locked_down(scratch_db)


def test_failed_revoke_after_failed_revision_keeps_original_error(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import app.db.migrations as migrations

    def broken_revoke(connection: object) -> None:
        raise RuntimeError("revoke failed")

    # env.py is executed afresh by each command, so it imports the patched helper.
    monkeypatch.setattr(migrations, "revoke_version_table_privileges", broken_revoke)
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", ["SELECT 1/0"], [])
    with pytest.raises(DBAPIError) as info:
        command.upgrade(alembic_env(versions), "head")
    assert getattr(info.value.orig, "sqlstate", None) == "22012"
    assert info.value.__notes__ == [
        "revoke on alembic_version after the failed run also failed (RuntimeError)"
    ]


def test_version_table_privileges_rerun_is_safe(
    alembic_env: MakeConfig, scratch_db: ScratchDb, tmp_path: Path
) -> None:
    versions = tmp_path / "versions"
    write_revision(versions, "s5a", [CREATE_PROBE], [DROP_PROBE])
    command.upgrade(alembic_env(versions), "head")
    acl = _scalar(scratch_db, "SELECT relacl::text FROM pg_class WHERE relname = 'alembic_version'")
    command.upgrade(alembic_env(versions), "head")
    _assert_version_table_locked_down(scratch_db)
    again = _scalar(
        scratch_db, "SELECT relacl::text FROM pg_class WHERE relname = 'alembic_version'"
    )
    assert again == acl
