"""Autogenerate on a `Vector(1536)` model writes the pgvector import and the revision runs
(BUILD-SEQUENCE.md:82 item 4); its rendered SQL goes through the squawk report (EXECUTION-PLAN.md
:303-305). The revision lives under `tmp_path` and runs on a scratch database."""

from __future__ import annotations

import sys
from collections.abc import Callable
from io import StringIO
from pathlib import Path
from types import ModuleType
from typing import Any

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from pgvector.sqlalchemy import Vector
from sqlalchemy import BigInteger, Column, MetaData, Table

from .conftest import ScratchDb, assert_no_scratch_revision_in

pytestmark = pytest.mark.allow_hosts(["localhost", "127.0.0.1", "::1"])

MakeConfig = Callable[[Path | None], Config]
SQUAWK = str(Path(sys.executable).parent / "squawk")


@pytest.fixture
def vec_probe() -> Table:
    """The probe lives on its own MetaData (passed to env.py through `config.attributes`), so
    the autogenerated revision holds only it, never the real models."""
    return Table(
        "vec_probe",
        MetaData(),
        Column("id", BigInteger, primary_key=True),
        Column("embedding", Vector(1536), nullable=False),
    )


def _probe_config(alembic_env: MakeConfig, versions: Path, probe: Table) -> Config:
    cfg = alembic_env(versions)
    cfg.attributes["target_metadata"] = probe.metadata
    return cfg


def _real_versions(repo_root: Path) -> list[str]:
    real = repo_root / "apps/api/alembic/versions"
    return sorted(p.name for p in real.iterdir() if p.name != "__pycache__")


def _autogenerate(cfg: Config, versions: Path) -> str:
    command.revision(
        cfg, autogenerate=True, rev_id="s5vec", message="vector probe", version_path=str(versions)
    )
    (written,) = versions.glob("s5vec_*.py")
    return written.read_text(encoding="utf-8")


def _column_type(db: ScratchDb) -> Any:
    with psycopg.connect(db.libpq, autocommit=True, connect_timeout=5) as conn:
        row = conn.execute(
            "SELECT format_type(a.atttypid, a.atttypmod) FROM pg_attribute a "
            "WHERE a.attrelid = to_regclass('vec_probe') AND a.attname = 'embedding'"
        ).fetchone()
    return None if row is None else row[0]


def test_autogenerate_vector_column(
    alembic_env: MakeConfig,
    scratch_db: ScratchDb,
    vec_probe: Table,
    tmp_path: Path,
    repo_root: Path,
    superuser_conn: psycopg.Connection[tuple[object, ...]],
) -> None:
    real_before = _real_versions(repo_root)
    versions = tmp_path / "versions"
    cfg = _probe_config(alembic_env, versions, vec_probe)
    source = _autogenerate(cfg, versions)
    assert "from pgvector.sqlalchemy import Vector" in source
    assert "Vector(1536)" in source
    assert "pgvector.sqlalchemy.vector.VECTOR" not in source

    command.upgrade(cfg, "head")
    assert _column_type(scratch_db) == "vector(1536)"
    command.downgrade(cfg, "base")
    assert _column_type(scratch_db) is None
    command.upgrade(cfg, "head")
    assert _column_type(scratch_db) == "vector(1536)"
    command.check(cfg)  # the model and the head agree

    assert _real_versions(repo_root) == real_before
    assert_no_scratch_revision_in(superuser_conn)


def test_autogenerated_vector_sql_is_squawk_reported(
    alembic_env: MakeConfig,
    vec_probe: Table,
    tmp_path: Path,
    script: Callable[[str], ModuleType],
    capsys: pytest.CaptureFixture[str],
) -> None:
    versions = tmp_path / "versions"
    cfg = _probe_config(alembic_env, versions, vec_probe)
    _autogenerate(cfg, versions)
    buffer = StringIO()
    cfg.output_buffer = buffer
    command.upgrade(cfg, "head", sql=True)
    rendered = tmp_path / "rendered.sql"
    rendered.write_text(buffer.getvalue(), encoding="utf-8")
    assert "SET lock_timeout = '5s';" in buffer.getvalue()

    capsys.readouterr()
    squawk_report = script("scripts/ci/squawk_report.py")
    assert squawk_report.report(rendered, squawk=SQUAWK) == 0
    out = capsys.readouterr().out
    assert "require-lock-timeout" not in out
    assert out.splitlines()[-1].startswith("squawk: ")
