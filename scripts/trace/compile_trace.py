#!/usr/bin/env python3
"""Compile docs/review/REQUIREMENTS-TRACE.md from the line-level register and its verdicts.

Usage: compile_trace.py [repo root]
Inputs: docs/trace/cNN.json (every spec line -> R-id) and cNN.map.json (a verdict per
normative R-id). Deterministic: re-run it after any register or verdict change; never hand-edit
the output.
"""
import collections
import glob
import json
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else '.'
d = os.path.join(root, 'docs/trace')
items, verdict = {}, {}
for f in sorted(glob.glob(os.path.join(d, 'c[0-9][0-9].json'))):
    for it in json.load(open(f, encoding='utf-8'))['items']:
        items[it['id']] = it
    m = f[:-5] + '.map.json'
    if os.path.exists(m):
        for e in json.load(open(m, encoding='utf-8'))['items']:
            verdict[e['id']] = e

ORDER = ['covered', 'covered-changed', 'gap', 'conflict', 'needs-client', 'other-team', 'later-phase']
ICON = {'covered': '✅', 'covered-changed': '🔁', 'gap': '⚠️', 'conflict': '❌', 'needs-client': '❓',
        'other-team': '🧩', 'later-phase': '⏭'}
norm = [i for i, it in items.items() if it['kind'] != 'info']
lines_total = sum(1 for _ in open(os.path.join(root, 'docs/source/system-arch-llms-full.txt'), encoding='utf-8'))
st = collections.Counter(verdict[i]['status'] for i in norm if i in verdict)
owner_gap = collections.Counter(verdict[i]['owner'] for i in norm if verdict.get(i, {}).get('status') == 'gap')
by_page = collections.defaultdict(collections.Counter)
for i in norm:
    if i in verdict:
        by_page[items[i].get('page', '?')][verdict[i]['status']] += 1


def esc(s):
    return re.sub(r'\s+', ' ', str(s)).replace('|', '\\|').strip()


def row(i):
    it, v = items[i], verdict[i]
    a, b = it['lines']
    return f"| {i} | L{a}{'' if a == b else f'–{b}'} | {esc(it['text'])} | {esc(v.get('ref', ''))} | {esc(v.get('note', ''))} |"


n = len(norm)
covered = st['covered'] + st['covered-changed']
out = [
    '# REQUIREMENTS TRACE — every client-spec statement vs our plan',
    '',
    '_Generated by `scripts/trace/compile_trace.py` from `docs/trace/`. Do not hand-edit:_',
    '_fix a verdict in `cNN.map.json` or the register in `cNN.json`, then re-run._',
    '',
    '## Answer',
    '',
    f'- **Every line of the client spec is traced.** All {lines_total:,} lines of the snapshot are in the register:',
    f'  {len(items):,} entries, of which {n:,} are checkable statements. `scripts/trace/check_coverage.py` proves 100% line coverage.',
    f'- **Every statement has a verdict**, with a reference, adversarially verified per chunk (`scripts/trace/check_mapping.py`).',
    f'- **{covered:,} of {n:,} ({100 * covered / n:.0f}%) are covered by our plan**: {st["covered"]:,} as written and',
    f'  {st["covered-changed"]:,} deliberately changed by an ADR, Canon row or recorded decision.',
    f'- **{st["gap"]:,} are gaps** (backend/DB {owner_gap["backend-db"]}, shared seams {owner_gap["shared"]}, ops {owner_gap["ops"]}, '
    f'AI team {owner_gap["ai-team"]}, FE team {owner_gap["fe-team"]}, client {owner_gap["client"]}).',
    f'- **{st["conflict"] + st["needs-client"]:,} need the team or client** ({st["conflict"]} conflicts, {st["needs-client"]} questions);',
    '  each points to a row in `TEAM-QUESTIONS.md`.',
    f'- {st["other-team"]:,} belong to the AI or FE team, and {st["later-phase"]:,} are marked Phase 2/3 by the site itself.',
    '',
    '| Status | Statements | Share |',
    '|---|---:|---:|',
]
out += [f'| {ICON[s]} {s} | {st[s]:,} | {100 * st[s] / n:.1f}% |' for s in ORDER]
out += ['', '## By page', '', 'Statements per site page (`# ` title), in source order. Pages with nothing to act on are marked ✔.', '',
        '| Page | ✅ | 🔁 | ⚠️ | ❌ | ❓ | 🧩 | ⏭ | Act on |', '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
seen = []
for i in sorted(norm, key=lambda x: items[x]['lines'][0]):
    p = items[i].get('page', '?')
    if p not in seen: seen.append(p)
for p in seen:
    c = by_page[p]
    act = c['gap'] + c['conflict'] + c['needs-client']
    out.append(f"| {esc(p)} | {c['covered']} | {c['covered-changed']} | {c['gap']} | {c['conflict']} | {c['needs-client']} | "
               f"{c['other-team']} | {c['later-phase']} | {act if act else '✔'} |")


def section(title, status, owners=None, intro=''):
    ids = [i for i in norm if verdict.get(i, {}).get('status') == status
           and (owners is None or verdict[i]['owner'] in owners)]
    if not ids: return []
    res = ['', f'## {title} ({len(ids)})', '']
    if intro: res += [intro, '']
    cur = None
    for i in sorted(ids, key=lambda x: items[x]['lines'][0]):
        p = items[i].get('page', '?')
        if p != cur:
            cur = p
            res += ['', f'### {esc(p)}', '', '| R-id | Lines | The site says | Ref | What is missing / differs |', '|---|---|---|---|---|']
        res.append(row(i))
    return res


out += section('❌ Conflicts: our plan contradicts the site', 'conflict', intro='Each row names its TEAM-QUESTIONS row. Until the team answers, we build the default recorded there.')
out += section('❓ Needs the team or client', 'needs-client')
out += section('⚠️ Gaps we own: backend + DB', 'gap', {'backend-db'}, 'Required for v1 and not yet in our plan. These feed DATABASE.md, BACKEND-ARCHITECTURE.md and the build steps.')
out += section('⚠️ Gaps on a shared seam (backend + AI or FE team)', 'gap', {'shared'})
out += section('⚠️ Gaps in delivery and operations', 'gap', {'ops'})
out += section('⚠️ Other gaps (client, AI team, FE team)', 'gap', {'client', 'ai-team', 'fe-team'})
out += ['', '## How to use this file', '',
        '- Before planning a step, grep this file for the step\'s tables, endpoints and terms; every ⚠️/❌/❓ row that touches the step goes into its `PLAN.md`.',
        '- To see the full context of a statement, open `docs/source/system-arch-llms-full.txt` at its lines.',
        '- To see every verdict (including ✅ ones), read `docs/trace/cNN.map.json`.',
        '- When the plan changes, update the verdicts, re-run `check_mapping.py`, then this script.', '']
path = os.path.join(root, 'docs/review/REQUIREMENTS-TRACE.md')
open(path, 'w', encoding='utf-8').write('\n'.join(out))
print(f'wrote {path}: {n} statements, {st["gap"]} gaps, {st["conflict"]} conflicts, {st["needs-client"]} questions, {os.path.getsize(path) // 1024} KB')
